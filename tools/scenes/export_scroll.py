"""
Exports the invitation scroll's rendered parts (node tools/scenes/render-scroll.cjs) for the website:

  * public/images/invitation/{roll,tied,band,bow,seal}-{1400,900}.webp — transparent; every layer but the
    roll shares one frame, so they stack exactly
  * public/images/invitation/seal-stamp.webp — the seal on its own, for the letter's closing
  * public/images/invitation/parchment.webp — a seamless parchment tile for the unrolled letter
  * src/data/scrollArt.generated.ts — where things sit in those frames (fractions), for the page's layout

Usage:  python tools/scenes/export_scroll.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
PUB = ROOT / "public" / "images" / "invitation"
TS = ROOT / "src" / "data" / "scrollArt.generated.ts"
URL = "/images/invitation"
WIDTHS = (1400, 900)
QUALITY = 84


def parchment(size: int = 768) -> None:
    """A tile of laid parchment that repeats without seams: soft mottling (noise filtered in the frequency
    domain, so it wraps), cotton fibres and flecks drawn wrapped round the edges, a faint laid-line texture."""
    rs = np.random.RandomState(19)

    def periodic(scale: float) -> np.ndarray:
        f = np.fft.fft2(rs.randn(size, size))
        ky, kx = np.meshgrid(np.fft.fftfreq(size), np.fft.fftfreq(size), indexing="ij")
        k = np.sqrt(kx**2 + ky**2)
        f *= np.exp(-((k * scale) ** 2))
        n = np.real(np.fft.ifft2(f))
        return (n - n.min()) / (n.max() - n.min())

    mott = 0.55 * periodic(60) + 0.3 * periodic(18) + 0.15 * periodic(5)
    laid = 0.5 + 0.5 * np.sin(np.arange(size) / size * 2 * np.pi * 96)[:, None] * np.ones((1, size))
    base = np.array([241, 228, 199], np.float32)[None, None, :]
    img = base * (0.9 + 0.13 * mott[..., None]) * (0.992 + 0.012 * laid[..., None])
    img[..., 2] *= 0.98
    pil = Image.fromarray(np.clip(img, 0, 255).astype("uint8"))
    d = ImageDraw.Draw(pil, "RGBA")
    for _ in range(2600):  # fibres, drawn again across each edge so the tile wraps
        x, y = rs.rand() * size, rs.rand() * size
        L, a = 6 + rs.rand() * 22, rs.rand() * np.pi
        pts = [(x + np.cos(a) * t + np.sin(t * 0.7) * 1.2, y + np.sin(a) * t + np.cos(t * 0.5)) for t in np.linspace(0, L, 7)]
        c = int(190 + rs.rand() * 50)
        col = (c, int(c * 0.92), int(c * 0.78), int(30 + rs.rand() * 45))
        for ox in (-size, 0, size):
            for oy in (-size, 0, size):
                d.line([(px + ox, py + oy) for px, py in pts], fill=col, width=1)
    for _ in range(230):  # flecks and a little foxing
        x, y, r = rs.rand() * size, rs.rand() * size, 0.4 + rs.rand() * (1.2 if rs.rand() < 0.9 else 3.2)
        c = int(110 + rs.rand() * 70)
        for ox in (-size, 0, size):
            for oy in (-size, 0, size):
                d.ellipse([x + ox - r, y + oy - r, x + ox + r, y + oy + r], fill=(c, int(c * 0.78), int(c * 0.55), int(28 + rs.rand() * 50)))
    pil.filter(ImageFilter.GaussianBlur(0.3)).save(PUB / "parchment.webp", quality=80, method=6)


def main() -> None:
    PUB.mkdir(parents=True, exist_ok=True)
    parchment()
    meta = {p: json.loads((OUT / f"scroll-{p}.meta.json").read_text()) for p in ("roll", "closed")}
    srcsets: dict[str, str] = {}
    for part, name in (("roll", "roll"), ("closed", "tied"), ("band", "band"), ("bow", "bow"), ("seal", "seal")):
        im = Image.open(OUT / f"scroll-{part}.png").convert("RGBA")
        entries = []
        for w in WIDTHS:
            h = round(im.height * w / im.width)
            im.resize((w, h), Image.LANCZOS).save(PUB / f"{name}-{w}.webp", quality=QUALITY, method=6)
            entries.append(f"{URL}/{name}-{w}.webp {w}w")
        srcsets[name] = ", ".join(reversed(entries))
    # the seal alone, cropped square round it, for the closing of the letter
    seal = Image.open(OUT / "scroll-seal.png").convert("RGBA")
    x0, y0, x1, y1 = seal.getbbox()
    side = max(x1 - x0, y1 - y0) + 8
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    stamp = seal.crop((cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2)).resize((360, 360), Image.LANCZOS)
    stamp.save(PUB / "seal-stamp.webp", quality=QUALITY, method=6)

    t, r = meta["closed"], meta["roll"]
    ts = f"""// Generated by tools/scenes/export_scroll.py — do not edit by hand.
// Where the scroll's parts sit in their pictures, as fractions of the picture (from the top left).

export const SCROLL_ART = {{
  /** the tied scroll and its overlays (band, bow, seal): one frame, stacked */
  tied: {{
    aspect: {t['frame']['aspect']:.5f},
    rollTop: {t['rolls']['top']:.5f},
    rollBottom: {t['rolls']['bottom']:.5f},
    paperLeft: {t['paper']['left']:.5f},
    paperRight: {t['paper']['right']:.5f},
    seal: {{ x: {t['seal']['x']:.5f}, y: {t['seal']['y']:.5f}, r: {t['seal']['r']:.5f} }},
  }},
  /** one roll on its rod, centred in its picture, the same width as the tied frame */
  roll: {{ aspect: {r['frame']['aspect']:.5f}, radius: {r['rollRadius']:.5f} }},
  src: {{
    roll: '{srcsets['roll']}',
    tied: '{srcsets['tied']}',
    band: '{srcsets['band']}',
    bow: '{srcsets['bow']}',
    seal: '{srcsets['seal']}',
    stamp: '{URL}/seal-stamp.webp',
  }},
}} as const
"""
    TS.write_text(ts)
    sizes = {p.name: p.stat().st_size // 1024 for p in sorted(PUB.iterdir())}
    print("exported (KB):", sizes)


if __name__ == "__main__":
    main()
